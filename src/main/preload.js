const { contextBridge, ipcRenderer } = require('electron');
const call = ch => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('api', {
  info: call('info'),
  mod: (key, fn = 'scan', arg) => ipcRenderer.invoke('mod', key, fn, arg),
  stop: call('stop'),
  clean: call('clean'),
  trashInfo: call('trashInfo'),
  emptyTrash: call('emptyTrash'),
  settings: call('settings'),
  setSettings: call('setSettings'),
  history: call('history'),
  clearHistory: call('clearHistory'),
  copy: call('copy'),
  openFDA: call('openFDA'),
  sizeOf: call('sizeOf'),
  onCleanProgress: fn => ipcRenderer.on('cleanProgress', (_e, p) => fn(p)),
  onMenu: fn => ipcRenderer.on('menu', (_e, cmd) => fn(cmd)),
  // Disk tab
  df: call('df'),
  pick: call('pick'),
  reveal: call('reveal'),
  home: call('home'),
  platform: call('platform'),
  checkPassword: call('checkPassword'),
  scan: call('scan'),
  tree: call('tree'),
  ghosts: call('ghosts'),
  remove: call('remove'),
  removeSudo: (paths, password) => ipcRenderer.invoke('removeSudo', { paths, password }),
  trash: call('trash'),
  emptyDir: call('emptyDir'),
  truncate: call('truncate'),
  reap: call('reap'),
  reapSudo: (entries, password) => ipcRenderer.invoke('reapSudo', { entries, password }),
});
